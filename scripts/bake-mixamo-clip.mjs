// Bakes a Mixamo FBX animation into a compact JS module for the Mr. Strange game.
//
//   node scripts/bake-mixamo-clip.mjs "path/to/Animation.fbx" games/mr-strange/src/character/slam-clip.js
//
// Works with "With Skin" or "Without Skin" downloads (30 fps, any keyframe reduction). The output holds the
// per-frame world POSITIONS of 25 joints, scaled to the hero's leg length, so it does not matter that
// Mixamo's bones have different axes or proportions. games/mr-strange/src/character/punch.js
// retargets it; register the clip there with a frame range, speed and impact frame.
import fs from 'node:fs';
import * as THREE from 'three';
import { FBXLoader } from 'three/examples/jsm/loaders/FBXLoader.js';

const [, , inFile, outFile] = process.argv;
if (!inFile || !outFile) { console.error('usage: node scripts/bake-mixamo-clip.mjs <in.fbx> <out.js>'); process.exit(1); }

// FBXLoader expects a browser for embedded textures; we only need the skeleton and the animation.
globalThis.window = { URL };
globalThis.document = { createElementNS: () => ({ addEventListener() {}, removeEventListener() {}, style: {}, set src(v) {} }) };
const warn = console.warn; console.warn = () => {};
const buf = fs.readFileSync(inFile);
const root = new FBXLoader().parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength), '');
console.warn = warn;

const clip = root.animations[0];
if (!clip) throw new Error('no animation in ' + inFile);
const JOINTS = ['Hips', 'Spine', 'Spine1', 'Spine2', 'Neck', 'Head', 'HeadTop_End',
  'LeftShoulder', 'LeftArm', 'LeftForeArm', 'LeftHand', 'LeftHandMiddle1',
  'RightShoulder', 'RightArm', 'RightForeArm', 'RightHand', 'RightHandMiddle1',
  'LeftUpLeg', 'LeftLeg', 'LeftFoot', 'LeftToeBase', 'RightUpLeg', 'RightLeg', 'RightFoot', 'RightToeBase'];
const nodes = JOINTS.map(n => root.getObjectByName('mixamorig' + n));
const missing = JOINTS.filter((_, i) => !nodes[i]);
if (missing.length) throw new Error('missing joints: ' + missing.join(', '));

const mixer = new THREE.AnimationMixer(root);
mixer.clipAction(clip).play();
root.updateMatrixWorld(true);
const at = (o) => new THREE.Vector3().setFromMatrixPosition(o.matrixWorld);

// Scale so the hero's hip-to-ankle height (rig.js: pelvis 0.980, ankle 0.085) matches the clip's.
const OUR_PELVIS = 0.980, OUR_ANKLE = 0.085;
const hips = at(nodes[0]).y, ankle = at(nodes[JOINTS.indexOf('LeftFoot')]).y;
const scale = (OUR_PELVIS - OUR_ANKLE) / (hips - ankle);

const count = Math.round(clip.duration * 30) + 1;
const frames = [];
for (let f = 0; f < count; f++) {
  mixer.setTime(f / 30);
  root.updateMatrixWorld(true);
  const row = [];
  for (const n of nodes) {
    const v = at(n);
    row.push(+(v.x * scale).toFixed(4), +((v.y - ankle) * scale + OUR_ANKLE).toFixed(4), +(v.z * scale).toFixed(4));
  }
  frames.push(row);
}

const name = inFile.split('/').pop();
fs.writeFileSync(outFile,
  `// Baked from Mixamo "${name}" (${count} frames @ 30 fps): joint positions in metres, scaled to this\n` +
  `// skeleton's leg length, feet on y = 0.085. Generated by scripts/bake-mixamo-clip.mjs: do not edit.\n` +
  `export default ${JSON.stringify({ fps: 30, joints: JOINTS, frames })};\n`);
console.log(`${name}: ${count} frames, ${clip.duration.toFixed(2)} s -> ${outFile}`);
